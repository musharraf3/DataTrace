from pathlib import Path

import pytest
from streamlit.testing.v1 import AppTest

APP = str(Path(__file__).resolve().parents[1] / "app.py")
INVESTIGATE = "③ Investigate metric change"


@pytest.fixture(autouse=True)
def no_key(monkeypatch):
    monkeypatch.setenv("DATATRACE_SKIP_DOTENV", "1")
    monkeypatch.delenv("MODEL_API_KEY", raising=False)
    monkeypatch.delenv("DATATRACE_PUBLIC_DEMO", raising=False)


def _app(mode="Offline checks (no AI)", scenario="Mini: duplicate join · 6 orders"):
    app = AppTest.from_file(APP, default_timeout=60).run()
    assert not app.exception
    next(w for w in app.radio if w.label == "Investigation mode").set_value(mode).run()
    next(w for w in app.selectbox if w.label == "Synthetic incident").select(scenario).run()
    return app


def _button(app, label):
    return next(widget for widget in app.button if widget.label == label)


def _markdown(app):
    return " ".join(element.value for element in app.markdown)


def test_offline_ui_displays_verdict_bridge_and_verified_fix():
    app = _app()
    _button(app, INVESTIGATE).click().run()
    assert not app.exception
    assert "Real growth + reporting defect" in _markdown(app)
    assert any(metric.label == "Verified corrected revenue" and "$1,300" in metric.value for metric in app.metric)
    assert any("Affected orders (1)" in element.value for element in app.subheader)
    assert any("matches the metric contract" in element.value for element in app.success)


def test_realistic_flagship_incident_runs_offline():
    app = _app(scenario="★ Black Friday + CRM migration · 4,122 orders")
    _button(app, INVESTIGATE).click().run()
    assert not app.exception
    assert "$13,964" in _markdown(app) or "$13,965" in _markdown(app)


def test_switching_incident_hides_stale_results():
    app = _app()
    _button(app, INVESTIGATE).click().run()
    next(w for w in app.selectbox if w.label == "Synthetic incident").select("Mini: missing refund rule · 6 orders").run()
    assert not app.metric
    _button(app, INVESTIGATE).click().run()
    assert not app.exception
    assert "Needs clarification" in _markdown(app)


def test_editing_sql_hides_previous_report():
    app = _app()
    _button(app, INVESTIGATE).click().run()
    next(w for w in app.text_area if w.label == "Current SQL").input("SELECT 1").run()
    assert not app.metric
    _button(app, INVESTIGATE).click().run()
    assert not app.exception
    assert app.error


def test_live_run_is_disabled_without_key():
    app = _app(mode="Live Meta agent")
    assert _button(app, INVESTIGATE).disabled


def test_manual_verification_rejects_equal_total_wrong_order():
    app = _app()
    _button(app, INVESTIGATE).click().run()
    next(w for w in app.text_area if w.label == "Candidate SQL to verify").input(
        "SELECT 1 AS order_id, 130000 AS revenue_cents").run()
    _button(app, "Verify candidate SQL").click().run()
    assert not app.exception
    assert any("violates" in element.value for element in app.warning)


def test_recorded_runs_replay_without_a_key():
    recorded = Path(APP).parent / "examples" / "recorded" / "realistic-crm_migration.json"
    if not recorded.exists():
        pytest.skip("Recorded runs are generated by scripts/record_runs.py")
    app = _app(mode="Recorded live run", scenario="★ Black Friday + CRM migration · 4,122 orders")
    _button(app, INVESTIGATE).click().run()
    assert not app.exception
    assert "Independently reviewed" in _markdown(app)


def test_recorded_clarification_pauses_then_resumes_after_answer():
    app = _app(mode="Recorded live run", scenario="Refund treatment undefined · 4,122 orders")
    _button(app, INVESTIGATE).click().run()
    assert not app.exception
    assert "THE AGENT PAUSED TO ASK YOU" in _markdown(app)
    _button(app, "Exclude refunds (gross sales)").click().run()
    assert not app.exception
    assert "Resumed after the analyst" in _markdown(app)


def test_deep_link_autoruns_recorded_replay():
    app = AppTest.from_file(APP, default_timeout=60)
    app.query_params["incident"] = "crm_migration"
    app.query_params["mode"] = "recorded"
    app.query_params["autorun"] = "1"
    app.query_params["fast"] = "1"
    app.run()
    assert not app.exception
    assert "Independently reviewed" in _markdown(app)


def test_deep_link_never_autoruns_live_mode(monkeypatch):
    monkeypatch.setenv("MODEL_API_KEY", "test-placeholder")
    monkeypatch.setattr("datatrace.meta.MetaClient.complete",
                        lambda *a, **k: pytest.fail("A link must never start a paid run"))
    app = AppTest.from_file(APP, default_timeout=60)
    app.query_params["incident"] = "crm_migration"
    app.query_params["mode"] = "live"
    app.query_params["autorun"] = "1"
    app.run()
    assert not app.exception
    assert not any("VERDICT" in m.value for m in app.markdown)
